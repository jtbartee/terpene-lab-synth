// Writes docs/DIVERSITY_REPORT.md: the diversity metrics of engine 2 against
// the v0.1 baseline, per style. Runs only with REPORT=1 (npm run report:diversity).

import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import {
  DRUM_GROUP, brayCurtis, contourProfile, durationHistogram, editDistance, identityBars, mapBrayCurtis, meanPairwise,
  onsetHistogram, sectionSequence, type BarLike,
} from '../../src/music/analysis';
import { generateBars } from '../../src/music/composer';
import { STYLE_IDS, STYLES } from '../../src/music/styles';
import { neutralParams } from '../../src/sonify/targets';
import { generateBars as legacyBars } from './legacy/composer-v1';

const P = neutralParams();
const SEEDS = [101, 202, 303, 404, 505, 606, 707, 808, 909, 1010, 1111, 1212];
const BARS = 192;
const f = (x: number) => x.toFixed(2);

it.runIf(process.env.REPORT === '1')('writes the diversity report', () => {
  const metrics: [string, (a: BarLike[], b: BarLike[]) => number][] = [
    ['Drum onsets', (a, b) => brayCurtis(onsetHistogram(a, DRUM_GROUP), onsetHistogram(b, DRUM_GROUP))],
    ['Bass onsets', (a, b) => brayCurtis(onsetHistogram(a, ['bass']), onsetHistogram(b, ['bass']))],
    ['Bass lengths', (a, b) => brayCurtis(durationHistogram(a, 'bass'), durationHistogram(b, 'bass'))],
    ['Melodic rhythm', (a, b) => brayCurtis(onsetHistogram(a, ['arp']), onsetHistogram(b, ['arp']))],
    ['Melodic contour', (a, b) => mapBrayCurtis(contourProfile(a, 'arp'), contourProfile(b, 'arp'))],
  ];
  const rows: string[] = [];
  const idRows: string[] = [];
  for (const style of STYLE_IDS) {
    const v2 = SEEDS.map((seed) => generateBars({ style, seed }, P, BARS) as BarLike[]);
    const v1 = SEEDS.map((seed) => legacyBars({ style, seed }, P, BARS) as unknown as BarLike[]);
    const cells = metrics.map(([, m]) => `${f(meanPairwise(v1, m))} → **${f(meanPairwise(v2, m))}**`);
    const form = f(meanPairwise(v2.map((b) => sectionSequence(b)), editDistance));
    rows.push(`| ${STYLES[style].label} | ${cells.join(' | ')} | ${form} |`);
    const i2 = v2.map(identityBars), i1 = v1.map(identityBars);
    idRows.push(`| ${STYLES[style].label} | ${metrics.slice(0, 2).map(([, m]) => `${f(meanPairwise(i1, m))} → **${f(meanPairwise(i2, m))}**`).join(' | ')} |`);
  }
  const md = `# Compositional diversity report

Generated by \`npm run report:diversity\` (tests/music/report.test.ts) on ${new Date().toISOString().slice(0, 10)}.

${SEEDS.length} seeds per style, ${BARS} bars each, key A natural minor, neutral profile parameters, default controls. Each cell is the mean
dissimilarity over all ${(SEEDS.length * (SEEDS.length - 1)) / 2} pairs of seeds: **v0.1 → engine 2**. 0 means every seed produced the same
thing; 1 means nothing in common. Rhythm metrics use onset positions only, so pitch and timbre changes do not count.
Definitions are in [TESTING.md](TESTING.md#diversity-metrics).

## Whole pieces

| Style | Drum onsets | Bass onsets | Bass lengths | Melodic rhythm | Melodic contour | Section order |
|---|---|---|---|---|---|---|
${rows.join('\n')}

Section order has no v0.1 value: v0.1 had no section roles (every piece was intro, then 16-bar sections named after an energy curve).

## Identities (each piece's first main section)

A whole-piece average blurs pieces that contain contrasting sections, so the core groove of each piece is also compared.
For v0.1, bars 16–47 (its core after the intro) stand in.

| Style | Drum onsets | Bass onsets |
|---|---|---|
${idRows.join('\n')}

Ambient and Experimental Drone have no drums in either engine. v0.1 drum values are partly noise: it re-rolled hi-hats
every bar, so two windows of the *same* v0.1 piece already differ (the "noise floor" used in the tests).
`;
  writeFileSync(new URL('../../docs/DIVERSITY_REPORT.md', import.meta.url), md);
});
